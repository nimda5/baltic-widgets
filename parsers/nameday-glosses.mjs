export function referenceEtymons(text){
 const found=[];
 for(const m of text.matchAll(/([\p{L}*'-]+)\s*\(\s*[“"']?([A-Za-z][A-Za-z ,;/-]{1,70})[”"']?\s*\)/gu)){
  if(/^(?:name|word|root|form|meaning|source|recorded|genitive)$/i.test(m[1]))continue;
  const gloss=glossary.get(m[2].toLowerCase().trim());if(gloss&&!found.some(p=>p.term===m[1]))found.push({term:m[1],gloss});
 }
 return found.slice(0,3);
}
